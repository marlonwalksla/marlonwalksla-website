#!/usr/bin/env python3
"""Exports the stamp icon library to stamp-icons.json so stamp-lib.js can draw the same stamps as page-embeds/stamps.py in the browser.
Run: python3 tools/export_stamp_icons.py   (re-run after adding or changing an icon in silhouettes.py / stamps.py)
Each icon: body (SVG inner markup, ink is the token @@INK@@), box [w,h,viewBox?], bb (measured bounding box), cen (ink weight center), size (scale factor)."""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PE = os.path.join(ROOT, "page-embeds")
sys.path.insert(0, PE)
import stamps
TOKEN = "@@INK@@"
names = re.findall(r'if name == "(\w+)"', open(os.path.join(PE, "stamps.py"), encoding="utf-8").read())
out = {}
for n in names:
    body, dims = stamps.icon(n, TOKEN)
    bb = stamps._BB[n if n in stamps._BB else "observatory_clean"]
    cen = stamps._CEN.get(n, (0.5, 0.5))
    out[n] = {"body": body, "box": [dims[0], dims[1]] + ([dims[2]] if len(dims) > 2 else []), "bb": bb, "cen": list(cen), "size": stamps._SIZE.get(n, 1.0)}
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extra_icons
out.update(extra_icons.ICONS)   # Nov 3, 2026: category pictures drawn from basic shapes
res = {"version": 1, "note": "Generated by tools/export_stamp_icons.py. Do not edit by hand.", "optical": stamps.OPTICAL, "icons": out}
with open(os.path.join(ROOT, "stamp-icons.json"), "w", encoding="utf-8") as f:
    json.dump(res, f, ensure_ascii=False, separators=(",", ":"))
print(len(out), "icons,", os.path.getsize(os.path.join(ROOT, "stamp-icons.json")), "bytes")
